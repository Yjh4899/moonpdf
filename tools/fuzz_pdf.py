"""Deterministic robustness fuzzing for the MoonPDF CLI.

Generates malformed variants of committed fixtures, runs the CLI with a timeout,
and classifies each result as ok, controlled error, crash, or timeout.

Usage:
    python tools/fuzz_pdf.py --cases 60 --out docs/fuzz-report.md
"""

from __future__ import annotations

import argparse
import json
import random
import subprocess
import sys
import time
from pathlib import Path

from fuzz_semantic import semantic_cases

ROOT = Path(__file__).resolve().parent.parent
FIXTURES = ROOT / "fixtures"


def variants(seed_path: Path, rng: random.Random) -> list[tuple[str, bytes]]:
    data = seed_path.read_bytes()
    name = seed_path.stem
    out: list[tuple[str, bytes]] = []
    for fraction in (0.1, 0.5, 0.9):
        out.append((f"{name}-trunc{int(fraction * 100)}", data[: max(0, int(len(data) * fraction))]))
    if data:
        flipped = bytearray(data)
        for _ in range(min(8, len(flipped))):
            pos = rng.randrange(len(flipped))
            flipped[pos] ^= 1 << rng.randrange(8)
        out.append((f"{name}-flip", bytes(flipped)))
        out.append((f"{name}-garbage", data + bytes(rng.randrange(256) for _ in range(128))))
    out.append((f"{name}-empty", b""))
    out.append((f"{name}-random", bytes(rng.randrange(256) for _ in range(rng.randrange(1, 2048)))))
    return out


def run_case(case: Path, timeout: int) -> dict:
    png = ROOT / "out" / "fuzz" / "case.png"
    if png.exists():
        png.unlink()
    started = time.perf_counter()
    try:
        proc = subprocess.run(
            ["moon", "run", "cmd/moonpdf", "--", str(case), str(png), "--scale", "1"],
            cwd=ROOT,
            capture_output=True,
            text=True,
            encoding="utf-8",
            errors="replace",
            timeout=timeout,
        )
        elapsed = round((time.perf_counter() - started) * 1000.0, 1)
        output = ((proc.stdout or "") + "\n" + (proc.stderr or "")).strip()
        if proc.returncode < 0:
            result = "crash"
        elif output.startswith("error:") or "\nerror:" in output:
            result = "controlled"
        elif proc.returncode == 0:
            result = "ok"
        else:
            result = "crash"
        return {
            "result": result,
            "ms": elapsed,
            "returncode": proc.returncode,
            "output": output[-400:],
        }
    except subprocess.TimeoutExpired:
        return {
            "result": "timeout",
            "ms": round((time.perf_counter() - started) * 1000.0, 1),
            "returncode": -1,
            "output": f"timeout after {timeout}s",
        }


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--cases", type=int, default=60)
    parser.add_argument("--timeout", type=int, default=30)
    parser.add_argument("--seed", type=int, default=20261121)
    parser.add_argument("--semantic-only", action="store_true")
    parser.add_argument("--out", type=Path, default=ROOT / "docs" / "fuzz-report.md")
    parser.add_argument("--json", type=Path, default=None)
    args = parser.parse_args()

    rng = random.Random(args.seed)
    work = ROOT / "out" / "fuzz"
    work.mkdir(parents=True, exist_ok=True)
    seeds = sorted(FIXTURES.glob("*.pdf"))
    if not seeds:
        print("no fixture PDFs")
        return 1
    cases: list[tuple[str, bytes]] = []
    if args.semantic_only:
        cases = semantic_cases()
    else:
        for seed in seeds:
            cases.extend(variants(seed, rng))
        cases.extend(semantic_cases())
    rng.shuffle(cases)
    cases = cases[: args.cases]

    rows = []
    for index, (name, data) in enumerate(cases, 1):
        path = work / f"{index:03d}-{name}.pdf"
        path.write_bytes(data)
        print(f"[{index}/{len(cases)}] {name}")
        outcome = run_case(path, args.timeout)
        outcome["case"] = name
        outcome["bytes"] = len(data)
        rows.append(outcome)

    summary = {
        "cases": len(rows),
        "ok": sum(1 for r in rows if r["result"] == "ok"),
        "controlled": sum(1 for r in rows if r["result"] == "controlled"),
        "crash": sum(1 for r in rows if r["result"] == "crash"),
        "timeout": sum(1 for r in rows if r["result"] == "timeout"),
    }
    if args.json:
        args.json.write_text(json.dumps({"summary": summary, "rows": rows}, indent=2), encoding="utf-8")

    lines = [
        "# Fuzz report",
        "",
        "Generated by `tools/fuzz_pdf.py`. Malformed variants of committed fixtures;",
        "each case runs the CLI with a per-case timeout.",
        "",
        f"- Cases: **{summary['cases']}**",
        f"- OK: **{summary['ok']}**",
        f"- Controlled errors: **{summary['controlled']}**",
        f"- Crashes: **{summary['crash']}**",
        f"- Timeouts: **{summary['timeout']}**",
        "",
        "| Case | Bytes | Result | ms | Output |",
        "| --- | --- | --- | --- | --- |",
    ]
    for row in rows:
        output = row["output"].replace("|", "\\|").replace("\n", " ")
        lines.append(
            f"| `{row['case']}` | {row['bytes']} | {row['result']} | {row['ms']} | {output} |"
        )
    args.out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(json.dumps(summary, indent=2))
    return 1 if summary["crash"] or summary["timeout"] else 0


if __name__ == "__main__":
    sys.exit(main())
