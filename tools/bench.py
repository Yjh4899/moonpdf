"""Wall-clock benchmark for the MoonPDF CLI.

Usage:
    python tools/bench.py --out docs/performance.md
    python tools/bench.py --cli "target/release/moonpdf" --reps 5

The default command is `moon run cmd/moonpdf --`, so timings include the MoonBit
runtime startup. Pass a built executable for pure render numbers.
"""

from __future__ import annotations

import argparse
import json
import platform
import shlex
import statistics
import subprocess
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "out" / "bench"

DEFAULT_CASES = [
    ("fixtures/shapes.pdf", 1),
    ("fixtures/shapes.pdf", 2),
    ("fixtures/font-embedded.pdf", 1),
    ("fixtures/font-embedded.pdf", 2),
    ("fixtures/font-cid.pdf", 1),
    ("fixtures/image-jpeg.pdf", 2),
    ("fixtures/pattern.pdf", 2),
    ("corpus/tracemonkey.pdf", 1),
    ("corpus/attention.pdf", 1),
]


def run_once(command: list[str], pdf: Path, png: Path, scale: int) -> float:
    if png.exists():
        png.unlink()
    args = command + [str(pdf), str(png), "--page", "1", "--scale", str(scale)]
    started = time.perf_counter()
    proc = subprocess.run(
        args,
        cwd=ROOT,
        capture_output=True,
        text=True,
        encoding="utf-8",
        errors="replace",
        timeout=300,
    )
    elapsed = (time.perf_counter() - started) * 1000.0
    if proc.returncode != 0 or not png.exists():
        raise RuntimeError(
            f"render failed ({proc.returncode}): "
            f"{(proc.stdout or '')[-200:]}{(proc.stderr or '')[-200:]}"
        )
    return elapsed


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--cli", default="moon run cmd/moonpdf --")
    parser.add_argument("--reps", type=int, default=3)
    parser.add_argument("--out", type=Path, default=ROOT / "docs" / "performance.md")
    parser.add_argument("--json", type=Path, default=None)
    parser.add_argument("--scale", type=int, default=0, help="override case scale")
    args = parser.parse_args()

    command = shlex.split(args.cli)
    OUT.mkdir(parents=True, exist_ok=True)
    rows = []
    for relative, scale in DEFAULT_CASES:
        pdf = ROOT / relative
        if not pdf.exists():
            print(f"skip missing {relative}")
            continue
        run_scale = args.scale or scale
        name = f"{pdf.stem}-s{run_scale}"
        png = OUT / f"{name}.png"
        try:
            run_once(command, pdf, png, run_scale)
            times = [run_once(command, pdf, png, run_scale) for _ in range(args.reps)]
        except Exception as error:  # noqa: BLE001 - report and continue
            print(f"skip {relative}: {error}")
            continue
        rows.append(
            {
                "pdf": relative,
                "scale": run_scale,
                "median_ms": round(statistics.median(times), 1),
                "min_ms": round(min(times), 1),
                "png_bytes": png.stat().st_size if png.exists() else 0,
                "runs": [round(value, 1) for value in times],
            }
        )
        print(
            f"{relative} scale {run_scale}: median {rows[-1]['median_ms']} ms, "
            f"png {rows[-1]['png_bytes']} bytes"
        )

    moon_version = ""
    try:
        moon_version = subprocess.check_output(
            ["moon", "version"], text=True, encoding="utf-8", errors="replace"
        ).strip()
    except Exception:
        pass
    machine = {
        "platform": platform.platform(),
        "processor": platform.processor(),
        "python": platform.python_version(),
        "moon": moon_version,
        "command": args.cli,
        "reps": args.reps,
    }
    if args.json:
        args.json.write_text(
            json.dumps({"machine": machine, "rows": rows}, indent=2),
            encoding="utf-8",
        )

    lines = [
        "# Performance",
        "",
        "Generated by `tools/bench.py`. Page 1, wall clock including CLI startup.",
        "",
        f"- Platform: `{machine['platform']}`",
        f"- CPU: `{machine['processor'] or 'unknown'}`",
        f"- MoonBit: `{machine['moon'] or 'unknown'}`",
        f"- CLI command: `{machine['command']}`",
        f"- Repetitions: **{machine['reps']}** (median reported)",
        "",
        "| PDF | Scale | Median (ms) | Min (ms) | PNG bytes |",
        "| --- | --- | --- | --- | --- |",
    ]
    for row in rows:
        lines.append(
            f"| `{row['pdf']}` | {row['scale']} | {row['median_ms']} | {row['min_ms']} | {row['png_bytes']} |"
        )
    medians = [row["median_ms"] for row in rows]
    if medians:
        lines.extend(
            [
                "",
                f"Overall median across cases: **{round(statistics.median(medians), 1)} ms**.",
                "",
                "These numbers include `moon run` startup and are intended for relative",
                "tracking. Build a native executable and pass `--cli` for throughput",
                "measurements.",
            ]
        )
    args.out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
